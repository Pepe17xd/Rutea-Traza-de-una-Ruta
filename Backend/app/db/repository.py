from abc import ABC, abstractmethod
from typing import Any


class Repository(ABC):
    @abstractmethod
    def create_mission(self, mission: dict[str, Any]) -> None: ...
    @abstractmethod
    def get_mission(self, mission_id: str) -> dict[str, Any] | None: ...
    @abstractmethod
    def update_mission(self, mission: dict[str, Any]) -> None: ...
    @abstractmethod
    def get_active_mission(self, robot_id: str) -> dict[str, Any] | None: ...
    @abstractmethod
    def latest_command_sequence(self, robot_id: str) -> int: ...
    @abstractmethod
    def list_missions(self, robot_id: str | None, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]: ...
    @abstractmethod
    def latest_telemetry(self, robot_id: str) -> dict[str, Any] | None: ...
    @abstractmethod
    def append_telemetry(self, data: dict[str, Any]) -> bool: ...
    @abstractmethod
    def list_trace(self, mission_id: str, limit: int, cursor: str | None) -> tuple[list[dict[str, Any]], str | None]: ...

